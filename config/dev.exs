import Config

# For development, we disable any cache and enable
# debugging and code reloading.
#
# The watchers configuration can be used to run external
# watchers to your application. For example, we can use it
# to bundle .js and .css sources.
config :veritas_web, Veritas.Web.Endpoint,
  # Binding to loopback ipv4 address prevents access from other machines.
  # Change to `ip: {0, 0, 0, 0}` to allow access from other machines.
  http: [ip: {127, 0, 0, 1}],
  check_origin: false,
  code_reloader: true,
  debug_errors: true,
  # The secret key base is generated for each boot rather than committed.
  # A committed key is a published key: it is in the repository, in every
  # clone of it, and in every fork — and a fork of a free project is exactly
  # where a signed cookie stops being a secret. Production requires
  # `SECRET_KEY_BASE` from the environment (`config/runtime.exs`), so a value
  # here was never going to be the one that mattered.
  #
  # The cost is that a development restart invalidates the session cookie and
  # the LiveView socket. That is a nuisance, not a risk.
  secret_key_base: Base.encode64(:crypto.strong_rand_bytes(48)),
  watchers: [
    esbuild: {Esbuild, :install_and_run, [:veritas_web, ~w(--sourcemap=inline --watch)]},
    tailwind: {Tailwind, :install_and_run, [:veritas_web, ~w(--watch)]}
  ]

# The GraphiQL IDE needs the schema, and the schema is not published outside
# development. Whether introspection is on is decided in `config/runtime.exs`,
# which is where `config_env()` can be read.

# ## SSL Support
#
# In order to use HTTPS in development, a self-signed
# certificate can be generated by running the following
# Mix task:
#
#     mix phx.gen.cert
#
# Run `mix help phx.gen.cert` for more information.
#
# The `http:` config above can be replaced with:
#
#     https: [
#       port: 4001,
#       cipher_suite: :strong,
#       keyfile: "priv/cert/selfsigned_key.pem",
#       certfile: "priv/cert/selfsigned.pem"
#     ],
#
# If desired, both `http:` and `https:` keys can be
# configured to run both http and https servers on
# different ports.

