defmodule Veritas.Web.Endpoint do
  use Phoenix.Endpoint, otp_app: :veritas_web

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_veritas_web_key",
    signing_salt: "IoiYrgCm",
    same_site: "Lax"
  ]

  @body_limit 1_000_000

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running "phx.digest".
  plug Plug.Static,
    at: "/",
    from: :veritas_web,
    gzip: not code_reloading?,
    only: Veritas.Web.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under
  # the :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # The body is read by `Plug.Parsers` before any route runs, so the limit on
  # it has to live here: a limit applied in a route would be applied after
  # the memory had already been spent. The cap is enforced twice — once on
  # the declared length, so an oversized request is refused without being
  # read at all, and once by the parser itself, so a request that lies about
  # its length is stopped too.
  plug Veritas.Web.RequestSizeLimit, max_bytes: @body_limit

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    length: @body_limit,
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug Veritas.Web.Router
end
